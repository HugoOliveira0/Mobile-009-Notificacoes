-- Execute no SQL Editor de um projeto Supabase dedicado à atividade.
-- A aula permite acesso público aos avisos; use somente dados fictícios.
begin;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  created_at timestamptz not null default now()
);

alter table public.notifications enable row level security;

-- Política de leitura/escrita pública apresentada no PDF.
drop policy if exists "Enabled read/write for all users" on public.notifications;
create policy "Enabled read/write for all users"
  on public.notifications
  for all
  to anon, authenticated
  using (true)
  with check (true);

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.notifications to anon, authenticated;
grant usage, select on sequence public.notifications_id_seq to anon, authenticated;

-- Equivale a habilitar Realtime para a tabela, sem duplicar a publicação.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end $$;

commit;
