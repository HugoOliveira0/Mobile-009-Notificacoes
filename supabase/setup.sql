-- Configuração do MOBILE 009: avisos públicos de aula, somente dados fictícios.
-- Permite ler e enviar. Clientes do aplicativo não podem alterar/apagar avisos.
begin;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 120),
  body text not null check (char_length(btrim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.notifications enable row level security;
revoke all on public.notifications from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select, insert on public.notifications to anon, authenticated;
grant usage on sequence public.notifications_id_seq to anon, authenticated;

drop policy if exists "Enabled read/write for all users" on public.notifications;
drop policy if exists "Read classroom notices" on public.notifications;
drop policy if exists "Send classroom notices" on public.notifications;
create policy "Read classroom notices"
  on public.notifications for select to anon, authenticated using (true);
create policy "Send classroom notices"
  on public.notifications for insert to anon, authenticated
  with check (
    char_length(btrim(title)) between 1 and 120
    and char_length(btrim(body)) between 1 and 2000
  );

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end $$;

commit;
